                            <li>Depression symptoms</li>
                            <li>Previous treatments</li>
                            <li>Current medications</li>
                            <li>Treatment goals</li>
                        </ul>
                        <p>If TMS is recommended, the provider performs a mapping session to identify the optimal treatment location and determine the correct stimulation intensity.</p>
                        <p>This personalized setup helps ensure your treatment is both safe and effective.</p>

                        <h2 class="text-3xl text-primary mt-10 mb-5" style="font-family: 'Bauhaus Soft', cursive;">What Happens During Each TMS Session?</h2>
                        <p>One of the biggest advantages of NeuroStar TMS is its simplicity.</p>
                        <p>During treatment:</p>
                        <ul class="list-disc pl-5 mb-6 space-y-2">
                            <li>You sit comfortably in a reclining chair.</li>
                            <li>The magnetic coil is positioned against your scalp.</li>
                            <li>The device delivers gentle magnetic pulses.</li>
                            <li>You remain awake throughout the session.</li>
                            <li>After treatment, you return to your normal activities.</li>
                        </ul>
                        <p>Many patients read, relax, or chat with staff during treatment. No recovery period is necessary.</p>

                        <h2 class="text-3xl text-primary mt-10 mb-5" style="font-family: 'Bauhaus Soft', cursive;">How Long Does TMS Treatment Take?</h2>
                        <p>Most NeuroStar treatment sessions last approximately 20 minutes.</p>
                        <p>A typical treatment schedule includes:</p>
                        <ul class="list-disc pl-5 mb-6 space-y-2">
                            <li>Five sessions per week</li>
                            <li>About four to six weeks of treatment</li>
                            <li>Follow-up taper sessions if recommended</li>
                        </ul>
                        <p>Consistency is important because the brain responds best to repeated stimulation over time.</p>

                        <h2 class="text-3xl text-primary mt-10 mb-5" style="font-family: 'Bauhaus Soft', cursive;">Does TMS Therapy Hurt?</h2>
                        <p>Most patients describe TMS as surprisingly comfortable.</p>
                        <p>During the first few sessions, you may notice:</p>
                        <ul class="list-disc pl-5 mb-6 space-y-2">
                            <li>Gentle tapping sensations</li>
                            <li>Mild scalp discomfort</li>
                            <li>Light muscle twitching near the forehead</li>
                        </ul>
                        <p>These sensations usually become less noticeable as treatment continues.</p>
                        <p>Unlike electroconvulsive therapy (ECT), TMS does not involve electrical currents passing through the brain, does not require anesthesia, and does not cause seizures in routine treatment.</p>

                        <h2 class="text-3xl text-primary mt-10 mb-5" style="font-family: 'Bauhaus Soft', cursive;">How Soon Do Patients Notice Results?</h2>
