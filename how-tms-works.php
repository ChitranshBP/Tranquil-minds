                        <h2 class="text-3xl text-primary mt-10 mb-5" style="font-family: 'Bauhaus Soft', cursive;">What Is TMS Therapy?</h2>
                        <p>Transcranial Magnetic Stimulation (TMS) is a non-invasive procedure that uses gentle magnetic pulses to stimulate nerve cells in areas of the brain involved in mood regulation.</p>
                        <p>Unlike medications, which circulate throughout the body and can affect multiple systems, TMS delivers targeted stimulation directly to the brain region associated with depression.</p>
                        <p>The treatment does not require surgery, anesthesia, sedation, or implanted devices. Patients remain awake throughout each session and can return to work, school, or daily activities immediately afterward.</p>
                        <p>NeuroStar TMS is one of the most widely used and clinically researched TMS systems available today, with millions of treatments delivered worldwide.</p>

                        <h2 class="text-3xl text-primary mt-10 mb-5" style="font-family: 'Bauhaus Soft', cursive;">Understanding Depression and the Brain</h2>
                        <p>Depression is more than feeling sad. It is a medical condition involving changes in brain function, chemistry, and communication between nerve cells.</p>
                        <p>Research has shown that many people with major depressive disorder have reduced activity in the left dorsolateral prefrontal cortex (DLPFC)—the area responsible for:</p>
                        <ul class="list-disc pl-5 mb-6 space-y-2">
                            <li>Mood regulation</li>
                            <li>Emotional processing</li>
                            <li>Decision-making</li>
                            <li>Concentration</li>
                            <li>Motivation</li>
                            <li>Problem-solving</li>
                        </ul>
                        <p>When this region becomes underactive, symptoms of depression may develop, including:</p>
                        <ul class="list-disc pl-5 mb-6 space-y-2">
                            <li>Persistent sadness</li>
                            <li>Fatigue</li>
                            <li>Loss of interest</li>
                            <li>Difficulty concentrating</li>
                            <li>Low motivation</li>
                            <li>Feelings of hopelessness</li>
                            <li>Changes in sleep</li>
                            <li>Appetite changes</li>
                        </ul>
                        <p>TMS therapy is designed to stimulate this underactive area and help restore healthier brain activity.</p>

                        <h2 class="text-3xl text-primary mt-10 mb-5" style="font-family: 'Bauhaus Soft', cursive;">How Does NeuroStar TMS Therapy Work?</h2>
                        <p>NeuroStar TMS uses a specialized magnetic coil positioned comfortably against your scalp.</p>
                        <p>The coil produces magnetic pulses similar in strength to those used during MRI scans. These pulses pass painlessly through the skull and activate neurons in targeted brain regions.</p>
                        <p>Once these neurons are stimulated repeatedly over several weeks, they begin forming stronger communication pathways.</p>
                        <p>Over time, this increased brain activity may improve emotional regulation and reduce symptoms of depression.</p>
                        <p>Think of it like exercising a muscle that has become weak. Repeated stimulation helps strengthen the brain circuits responsible for healthy mood function.</p>

                        <h2 class="text-3xl text-primary mt-10 mb-5" style="font-family: 'Bauhaus Soft', cursive;">Why Magnetic Stimulation Helps Depression</h2>
                        <p>Depression often disrupts communication between different brain networks.</p>
                        <p>NeuroStar therapy helps:</p>
                        <ul class="list-disc pl-5 mb-6 space-y-2">
                            <li>Increase activity in underactive brain regions</li>
                            <li>Improve communication between neurons</li>
                            <li>Encourage neuroplasticity (the brain's ability to reorganize itself)</li>
                            <li>Strengthen mood regulation pathways</li>
                            <li>Improve emotional resilience over time</li>
                        </ul>
                        <p>Rather than masking symptoms, TMS works by helping restore healthier patterns of brain activity.</p>

