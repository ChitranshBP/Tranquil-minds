                        <p>TMS therapy is commonly recommended for adults diagnosed with Major Depressive Disorder who have not experienced sufficient improvement from antidepressant medications.</p>
                        <p>You may be a candidate if you:</p>
                        <ul class="list-disc pl-5 mb-6 space-y-2">
                            <li>Have depression that hasn't improved after trying medications</li>
                            <li>Experienced unwanted medication side effects</li>
                            <li>Prefer a non-drug treatment option</li>
                            <li>Want to avoid long-term medication dependence</li>
                            <li>Continue experiencing symptoms despite therapy</li>
                        </ul>
                        <p>A comprehensive psychiatric evaluation at Tranquil Minds Mental Health helps determine whether NeuroStar TMS is appropriate for your individual needs.</p>

