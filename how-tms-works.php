                        <p>Transcranial Magnetic Stimulation (TMS) therapy has become one of the most promising non-medication treatments for depression, especially for people with treatment-resistant depression. At Tranquil Minds Mental Health in Monticello, Minnesota, patients have access to NeuroStar® Advanced Therapy, an FDA-cleared, non-invasive treatment designed to help improve symptoms of depression by stimulating specific areas of the brain.</p>
                        
